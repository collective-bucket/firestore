#!/usr/bin/env node
"use strict";

// Concatenates rules/*.rules (sorted by name) into firestore.rules.
// --check fails when the committed firestore.rules is out of date.
var fs = require("fs");
var path = require("path");

var root = path.join(__dirname, "..");
var dir = path.join(root, "rules");
var target = path.join(root, "firestore.rules");

var banner = "// GENERATED by scripts/build.js from rules/*.rules. Do not edit by hand.\n";
var parts = fs
  .readdirSync(dir)
  .filter(function (file) {
    return file.endsWith(".rules");
  })
  .sort()
  .map(function (file) {
    var text = fs.readFileSync(path.join(dir, file), "utf8");
    return text.endsWith("\n") ? text : text + "\n";
  });
var output = banner + parts.join("");

if (process.argv.indexOf("--check") >= 0) {
  var current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== output) {
    console.error("firestore.rules is out of date: run npm run build");
    process.exit(1);
  }
  console.log("firestore.rules is up to date");
} else {
  fs.writeFileSync(target, output);
  console.log("wrote firestore.rules");
}
